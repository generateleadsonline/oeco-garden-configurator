"""Builds src/configurator-pdf-assets.js: the PDF's fonts and Oeco logos as data URLs.

python3 tools/build-pdf-assets.py

Fonts: Manrope 400/700 (OFL) for text, and Cormorant 500/700 (OFL), the heading face of
oecogardenrooms.co.uk, converted from Oeco's own woff2 files (research/brand) to TTF in
tools/fonts. Logos: Oeco's SVG logos (research/brand/oeco-logo*.svg), drawn by headless Chrome
into research/raw/brand/*.png without redrawing, then resized.
"""
import base64
import io
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / 'research' / 'raw' / 'brand'


def logo(path, width):
    im = Image.open(path).convert('RGBA')
    im = im.crop(im.getbbox())
    h = round(im.height * width / im.width)
    im = im.resize((width, h), Image.Resampling.LANCZOS)
    out = io.BytesIO(); im.save(out, format='PNG', optimize=True)
    return out.getvalue(), im.size


dark, dark_size = logo(RAW / 'oeco-logo-dark.png', 640)
white, white_size = logo(RAW / 'oeco-logo-white.png', 640)
fonts = {k: base64.b64encode((ROOT / 'tools' / 'fonts' / f).read_bytes()).decode() for k, f in
         {'regular': 'manrope-400.ttf', 'bold': 'manrope-700.ttf', 'heading': 'cormorant-700.ttf'}.items()}
url = lambda b: 'data:image/png;base64,' + base64.b64encode(b).decode()
js = ('// Generated by tools/build-pdf-assets.py: do not edit.\n'
      f'export const PDF_FONTS = {json.dumps(fonts)};\n'
      f'export const PDF_LOGO = {json.dumps(url(dark))};\n'
      f'export const PDF_LOGO_SIZE = {json.dumps(dark_size)};\n'
      f'export const PDF_LOGO_WHITE = {json.dumps(url(white))};\n'
      f'export const PDF_LOGO_WHITE_SIZE = {json.dumps(white_size)};\n')
(ROOT / 'src' / 'configurator-pdf-assets.js').write_text(js)
print('logos', dark_size, white_size, 'assets', len(js) // 1024, 'KB')
